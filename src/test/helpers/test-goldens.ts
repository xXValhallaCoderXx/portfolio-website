const dt = 1 / 60;
const RUN_WING = GLIDERS[0];

// A step's legacy bits as the controls a pure flight is flown by.
function controlsOf(bits: number, controls: FlightInput) {
  const left = !!(bits & 1), right = !!(bits & 2), ears = (bits & 12) === 12;
  controls.turn = Number(right) - Number(left); controls.ears = ears;
  controls.deepBrake = !ears && !!(bits & 16);
  controls.brake = !ears && (!!(bits & 4) || controls.deepBrake);
  controls.bar = !ears && !controls.brake && ((left && right) || !!(bits & 8));
  return controls;
}

/** The keyboard runs: TST's keys on the EN-A over three skies, and once with the ears pulled for three seconds. */
export const GOLDEN_RUNS = Object.freeze([
  { name: 'centred soaring, sky 1', seed: 1, ears: false },
  { name: 'soaring and weather, sky 7', seed: 7, ears: false },
  { name: 'opposite wind soaring, sky 2', seed: 2, ears: false },
  { name: 'ears and reopening, sky 2', seed: 2, ears: true },
]);

export function captureRun(plan: typeof GOLDEN_RUNS[number]) {
  const world = startRun(createRunWorld({ sky: createCloudbaseRun(), meet: createMeet(), bells: createBells(), style: createComboStyle(), wing: RUN_WING }), plan.seed);
  const keys = createReferenceKeys({ ...TST, plan: planFor(RUN_WING) }), recorder = createRecorder();
  let ended = null;
  while (!ended && recorder.steps < MAX_STEPS) {
    let bits = keys(world);
    const elapsed = world.sky.state.elapsed;
    if (plan.ears && elapsed >= 75 && elapsed < 78) bits = (bits & 3) | INPUT.ears;
    if (!recorder.push(bits)) throw new Error('The canonical recorder overflowed');
    ended = stepBits(world, bits);
  }
  const reason = ended ?? 'quit';
  finishRun(world, reason);
  const sheet = summariseRun(world, reason);
  const link = encodeLog({ simVersion: SIM_VERSION, glider: RUN_WING, seed: plan.seed, day: 0, total: sheet.total, peak: sheet.peak }, recorder.bits, recorder.steps);
  return { name: plan.name, simVersion: SIM_VERSION, glider: RUN_WING, source: 'Chromium computed canonical digital input',
    scenario: plan.ears ? 'ears' : 'soaring', seed: plan.seed, link, sheet };
}

type ManeuverWorld = { g: ReturnType<typeof createFlight>; watch: ReturnType<typeof createSwingWatch>; style: ReturnType<typeof createStyle> };
/** A pure flight's bodies, watch and style, its derived angles to 1e-12 rad (the cross-engine precision of V8's inverse trig). */
export function maneuverSnapshot({ g, watch, style }: ManeuverWorld, stallFrames: number) {
  return JSON.parse(JSON.stringify({ loops: g.loops, pos: { ...g.pos }, vel: { ...g.pilot.vel }, canopy: { ...g.canopy.pos },
    canopyVel: { ...g.canopy.vel }, quaternion: { ...g.canopy.q }, omega: { ...g.canopy.omega },
    bank: Math.round(g.bank * 1e12) / 1e12, pitch: Math.round(g.pitch * 1e12) / 1e12, energy: g.physical.energy, stallFrames,
    watch: { breaks: watch.state.breaks, moves: watch.state.moves, kind: watch.state.moveKind, band: watch.state.moveBand, calm: watch.state.calm },
    style: { total: style.state.total, pending: style.state.pending, landed: style.state.landed, lost: style.state.lost,
      loops: style.state.mostLoops, wingovers: style.state.wingovers, pitch: style.state.pitch } }));
}

/** A whole maneuver on the classic wing, flown and caught by the flight coach's own cards: an orbit, a wingover or a pitch. */
export function captureManeuver(kind: 'orbit' | 'wingover' | 'pitch') {
  const origin = { x: 0, y: kind === 'orbit' ? 2000 : 1000, z: 0 };
  const g = createFlight({ ...origin }), watch = createSwingWatch(), style = createStyle(), recorder = createRecorder();
  const controls = { turn: 0, brake: false, deepBrake: false, bar: false, ears: false }, world = { g, watch, controls };
  const coach = createFlightCoach();
  let stallFrames = 0, following = false, pending: CoachMessage | null = null, applyAt = -1;
  for (let tick = 0; tick < 5000 && style.state.total === 0; tick++) {
    if (kind === 'orbit') {
      const exiting = tick >= 580;
      controls.turn = exiting ? 0 : tick < 285 ? -1 : 1;
      controls.deepBrake = tick < 12;
      controls.bar = !exiting && !controls.deepBrake;
      controls.brake = controls.deepBrake || exiting && g.pitch < 0;
    } else {
      if (!following) {
        controls.turn = kind === 'wingover' ? tick < 270 ? -1 : 1 : 0;
        controls.deepBrake = kind === 'pitch' ? tick % 390 < 108 : tick < 12;
        controls.brake = controls.deepBrake;
      }
      if (pending && tick >= applyAt) {
        const raw: Record<string, boolean> = { left: controls.turn < 0, right: controls.turn > 0, brake: controls.brake, deepBrake: controls.deepBrake, bar: controls.bar, ears: false };
        for (const key of pending.release) raw[key] = false;
        if (pending.release.includes('brake')) raw.deepBrake = false;
        for (const key of pending.hold) raw[key] = true;
        if (pending.hold.includes('brake')) raw.deepBrake = pending.brakeDepth === 'deep';
        controls.turn = Number(raw.right) - Number(raw.left); controls.brake = raw.brake; controls.deepBrake = raw.deepBrake; controls.bar = raw.bar;
        pending = null;
      }
    }
    recorder.push(inputBits({ left: controls.turn < 0, right: controls.turn > 0, brake: controls.brake, deepBrake: controls.deepBrake, bar: controls.bar, ears: false }));
    stepFlight(g, controls, {}, dt);
    watch.step(dt, g, false, controls); style.step(dt, world);
    stallFrames += g.stall > 0 ? 1 : 0;
    if (kind !== 'orbit') {
      const raw = { left: controls.turn < 0, right: controls.turn > 0, brake: controls.brake, deepBrake: controls.deepBrake, bar: controls.bar, ears: false };
      const message = coach.step(dt, { g, watch: watch.state, style: style.state, input: raw, clearance: 1000, fogClearance: 1000, eligible: true });
      if (message?.context === kind) following = true;
      if (following && !pending && message && (message.hold.some((key) => !raw[key as keyof typeof raw]) ||
        message.release.some((key) => raw[key as keyof typeof raw]) || message.hold.includes('brake') && !!raw.deepBrake !== (message.brakeDepth === 'deep'))) {
        pending = message; applyAt = tick + 13;
      }
    }
  }
  const snapshot = maneuverSnapshot({ g, watch, style }, stallFrames);
  if (snapshot.style.total <= 0 || snapshot.stallFrames || snapshot.watch.breaks || snapshot.watch.calm < 1 ||
    snapshot.loops !== (kind === 'orbit' ? 1 : 0) || g.pos.y >= origin.y) throw new Error(`${kind} did not complete and recover cleanly`);
  const link = encodeLog({ simVersion: SIM_VERSION, glider: 'classic', seed: 0, day: 0, total: snapshot.style.total, peak: origin.y }, recorder.bits, recorder.steps);
  return { name: `complete physical ${kind} and recovery`, source: 'Chromium computed digital maneuver and stable recovery',
    pureFlight: true, simVersion: SIM_VERSION, kind, origin, tick: recorder.steps, link, snapshot };
}

/** A maneuver's logged steps flown again on the classic wing: its snapshot. */
export function replayManeuver(record: { origin: Vector3 }, bits: ArrayLike<number>) {
  const g = createFlight({ ...record.origin }), watch = createSwingWatch(), style = createStyle(), controls: FlightInput = {}, world = { g, watch, controls };
  let stallFrames = 0;
  for (let i = 0; i < bits.length; i++) {
    stepFlight(g, controlsOf(bits[i], controls), {}, dt);
    watch.step(dt, g, false, controls); style.step(dt, world);
    stallFrames += g.stall > 0 ? 1 : 0;
  }
  return maneuverSnapshot({ g, watch, style }, stallFrames);
}

// The lessons' telemetry derived by inverse trig, to the cross-engine precision of V8's last bit.
const ANGLES = new Set(['bank', 'pitch', 'rollRate', 'pitchRate', 'trackRate', 'yawRate', 'rollAcceleration', 'leftBrake', 'rightBrake', 'leftBrakeTarget', 'rightBrakeTarget']);
export const lessonSnapshot = <T>(value: T): T => JSON.parse(JSON.stringify(value, (key, item) =>
  ANGLES.has(key) && typeof item === 'number' ? Math.round(item * 1e11) / 1e11 : item));

/**
 * A Training lesson on the classic wing (pitch or wingover), flown in a still thermal of 5.5 m/s by
 * a pilot who follows its cards `delay` seconds late, kept in this page's own store: the lesson is
 * learned as it banks, and the best kept stays the store's.
 */
export function captureLesson(kind: LessonId, side: number, delay: number) {
  clearStore();
  const saved = readStore();
  saved.best = { total: 123, score: 123, peak: 800 };
  saved.learnedLessons = kind === 'pitch' ? [] : ['pitch'];
  writeStore(saved);
  const origin = { x: -side * 21, y: 1000, z: 0 }, source = { x: 0, z: 0, r: 80, s: 5.5 }, weather = { windX: 0, windZ: 0, thermals: [source] };
  const g = createFlight({ ...origin }), watch = createSwingWatch(), style = createStyle(), controls: FlightInput = {}, world = { g, watch, controls }, air = {};
  const recorder = createRecorder();
  const lessons = createTrickLessons({ learned: () => readStore().learnedLessons, onLearned: (id) => learnTrickLesson(id) });
  let input = { left: side < 0, right: side > 0, brake: true, deepBrake: false, bar: false, ears: false };
  let pending: { at: number; input: typeof input } | null = null, message: CoachMessage | null = null;
  for (let tick = 0; tick < 2700; tick++) {
    if (pending && pending.at <= tick) { input = pending.input; pending = null; }
    recorder.push(inputBits(input));
    sampleAtmosphere(g.pos, weather, air);
    Object.assign(controls, { turn: Number(input.right) - Number(input.left), brake: input.brake, deepBrake: input.deepBrake, bar: input.bar, ears: input.ears });
    stepFlight(g, controls, air, dt); watch.step(dt, g, false, controls); style.step(dt, world);
    if (tick < 600) continue;
    message = lessons.step(dt, { g, watch: watch.state, style: style.state, input, air, clearance: g.pos.y, fogClearance: g.pos.y });
    if (message && !pending) {
      const next: Record<string, boolean> = { ...input };
      for (const key of message.release) next[key] = false;
      if (message.release.includes('brake')) next.deepBrake = false;
      for (const key of message.hold) next[key] = true;
      if (message.hold.includes('brake')) next.deepBrake = message.brakeDepth === 'deep';
      if (JSON.stringify(next) !== JSON.stringify(input)) pending = { at: tick + Math.round(delay * 60) + 1, input: next as typeof input };
    }
    if (lessons.state.phase === 'banked') break;
  }
  if (lessons.state.phase !== 'banked' || watch.state.moves !== 1 || watch.state.breaks || style.state.lost || watch.state.calm < 1) {
    throw new Error(`Incomplete physical lesson ${kind} ${side} ${delay}`);
  }
  const link = encodeLog({ simVersion: SIM_VERSION, glider: 'classic', seed: 0, total: style.state.total, peak: origin.y }, recorder.bits, recorder.steps);
  return { kind, side, delay, simVersion: SIM_VERSION, origin, source, link, snapshot: lessonSnapshot({ g, watch: watch.state, style: style.state }),
    learned: readStore().learnedLessons, keptBest: readStore().best, feedback: message?.title ?? '', phase: lessons.state.phase,
    awarded: lessons.state.awarded, steps: recorder.steps };
}

/** A lesson's logged steps flown again in its thermal on the classic wing: its snapshot. */
export function replayLesson(record: { origin: Vector3; source: { x: number; z: number; r: number; s: number } }, bits: ArrayLike<number>) {
  const g = createFlight({ ...record.origin }), watch = createSwingWatch(), style = createStyle(), controls: FlightInput = {}, world = { g, watch, controls }, air = {};
  for (let i = 0; i < bits.length; i++) {
    const step = bits[i], ears = (step & 12) === 12;
    Object.assign(controls, { turn: Number(!!(step & 2)) - Number(!!(step & 1)), ears,
      deepBrake: !ears && !!(step & 16), brake: !ears && !!(step & 20), bar: !ears && !!(step & 8) });
    sampleAtmosphere(g.pos, { windX: 0, windZ: 0, thermals: [record.source] }, air);
    stepFlight(g, controls, air, dt); watch.step(dt, g, false, controls); style.step(dt, world);
  }
  return lessonSnapshot({ g, watch: watch.state, style: style.state });
}

/** A full stall or a frontal on the classic wing in still air, flown out by the flight coach's cards `delay` seconds late. */
export function captureRecoveryFlight(scenario: 'stall' | 'frontal', delay: number) {
  const flown = recoveryFlight({ scenario, delay, record: true });
  if (flown.recoveredAt === null || flown.recoverySeconds === null || flown.recoverySeconds > 30 || flown.recoveryHeightLoss > 150) {
    throw new Error(`Failed recovery ${scenario} ${delay}`);
  }
  const link = encodeLog({ simVersion: SIM_VERSION, glider: 'classic', seed: 0, total: 0, peak: flown.origin.y }, flown.bits, flown.bits.length);
  return { pureFlight: true, scenario, delay, simVersion: SIM_VERSION, origin: flown.origin, link,
    snapshot: lessonSnapshot({ g: flown.g, watch: flown.watch, style: flown.style }),
    metrics: { seconds: flown.recoverySeconds, heightLoss: flown.recoveryHeightLoss, backflySeconds: flown.reverseSeconds,
      folds: flown.folds, minimumInflation: flown.minimumInflation }, phases: flown.phases };
}

